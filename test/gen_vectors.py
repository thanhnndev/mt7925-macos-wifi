# Generates wpa_vectors.h from python reference implementations (hashlib/hmac/cryptography).
import hashlib, hmac, os, random
from cryptography.hazmat.primitives.keywrap import aes_key_wrap

random.seed(7)
def rb(n): return bytes(random.randrange(256) for _ in range(n))
def arr(name, b): return "static const uint8_t %s[] = {%s};\n" % (name, ",".join("0x%02x" % x for x in b))
def prf(key, label, data, n):
    out = b""; i = 0
    while len(out) < n:
        out += hmac.new(key, label + b"\0" + data + bytes([i]), hashlib.sha1).digest(); i += 1
    return out[:n]

o = "// SPDX-License-Identifier: BSD-3-Clause-Clear\n// Copyright (c) 2026 thanhnndev and contributors\n// generated by gen_vectors.py\n"
o += arr("v_sha_in", b"abc" * 50) + arr("v_sha_out", hashlib.sha1(b"abc" * 50).digest())
k = rb(100)
o += arr("v_hmac_key", k) + arr("v_hmac_d1", b"hello ") + arr("v_hmac_d2", b"world")
o += arr("v_hmac_out", hmac.new(k, b"hello world", hashlib.sha1).digest())
ssid = b"TestNet"; pw = b"correct horse battery"
o += arr("v_ssid", ssid) + arr("v_pass", pw) + arr("v_pmk", hashlib.pbkdf2_hmac("sha1", pw, ssid, 4096, 32))
pmk = hashlib.pbkdf2_hmac("sha1", pw, ssid, 4096, 32)
aa, spa, an, sn = rb(6), rb(6), rb(32), rb(32)
data = min(aa, spa) + max(aa, spa) + min(an, sn) + max(an, sn)
ptk = prf(pmk, b"Pairwise key expansion", data, 48)
o += arr("v_aa", aa) + arr("v_spa", spa) + arr("v_an", an) + arr("v_sn", sn) + arr("v_ptk", ptk)
kek = rb(16); pt = rb(56)
o += arr("v_kek", kek) + arr("v_wrapped", aes_key_wrap(kek, pt)) + arr("v_unwrapped", pt)
# EAPOL frame with MIC
kck = ptk[:16]
frame = bytearray(99 + 8)
frame[0] = 2; frame[1] = 3; frame[2:4] = (95 + 8).to_bytes(2, "big"); frame[4] = 2
frame[5:7] = (0x010a).to_bytes(2, "big"); frame[7:9] = (16).to_bytes(2, "big")
frame[9:17] = rb(8); frame[17:49] = rb(32); frame[97:99] = (8).to_bytes(2, "big"); frame[99:] = rb(8)
mic = hmac.new(kck, bytes(frame), hashlib.sha1).digest()[:16]
frame[81:97] = mic
o += arr("v_eapol", bytes(frame))
open("wpa_vectors.h", "w").write(o)
