"""Generate kexts/itlmt7925Native/itlmt7925_iface_stubs.inc from the verified header IO80211InfraProtocol.h.

The Family's request routing calls 190 pure virtuals of IO80211InfraProtocol (slots 467-656) plus IO80211SkywalkInterface::
setMacAddress (slot 417, the 191st pure slot). A native interface must override every one of them or the class stays abstract.
Stage 2 has no radio, so each handler answers kIOReturnUnsupported. The declarations are written from the header line by line
(name, parameter list, slot comment), so a regenerated header regenerates the stubs.

  python3 tools/gen_native_iface.py            # rewrite the .inc
  python3 tools/gen_native_iface.py --check    # exit 1 if the committed .inc differs
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDRS = [os.path.join(ROOT, 'kexts/itlmt7925/io80211', h) for h in ('IO80211SkywalkInterface.h', 'IO80211InfraProtocol.h')]
OUT = os.path.join(ROOT, 'kexts/itlmt7925Native/itlmt7925_iface_stubs.inc')
PURE = re.compile(r'/\*\s*(\d+)\s*\*/\s*virtual\s+(\S+)\s+(\w+)\((.*?)\)\s*=\s*0;')


def pure_slots():
    out = []
    for h in HDRS:
        for line in open(h):
            m = PURE.search(line)
            if m:
                out.append((int(m.group(1)), m.group(2), m.group(3), m.group(4)))
    return sorted(out)


def render():
    slots = pure_slots()
    for _, ret, _, _ in slots:
        assert ret == 'IOReturn', ret       # every pure slot returns IOReturn in the header (guess tagged there)
    o = ['// GENERATED by tools/gen_native_iface.py from IO80211SkywalkInterface.h + IO80211InfraProtocol.h. Do not edit by hand.',
         '// %d pure virtuals of the Family (slot 417 + 467..656). Stage 2 has no radio: every handler is unsupported.' % len(slots),
         '#ifdef ITL_IFACE_DECLS']
    for slot, ret, name, params in slots:
        o.append('    %s %s(%s) override;   // slot %d' % (ret, name, params, slot))
    o.append('#endif')
    o.append('#ifdef ITL_IFACE_DEFS')
    for slot, ret, name, params in slots:
        # unnamed parameters: the body never touches them
        o.append('%s itlmt7925WifiInterface::%s(%s) { return kIOReturnUnsupported; }' % (ret, name, params))
    o.append('#endif')
    return '\n'.join(o) + '\n'


def main():
    text = render()
    if '--check' in sys.argv:
        return 0 if open(OUT).read() == text else 1
    open(OUT, 'w').write(text)
    print('wrote %s (%d slots)' % (os.path.relpath(OUT, ROOT), len(pure_slots())))
    return 0


if __name__ == '__main__':
    sys.exit(main())
